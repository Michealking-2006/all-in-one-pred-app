// Run after changing files under src/: node scripts/build-shell.mjs
// Walks the static import graph from src/App.js and writes it into index.html
// as <link rel="modulepreload"> tags. Without them the browser discovers each
// module only after the previous one has downloaded and parsed (a waterfall of
// ~25 round trips); with them they all download in parallel.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const seen = new Set();

function walk(rel) {
  if (seen.has(rel)) return;
  seen.add(rel);
  const file = path.join(root, rel);
  if (!fs.existsSync(file)) return;
  const source = fs.readFileSync(file, "utf8");
  // Static imports only: `import ... from "./x.js"` and `export ... from "./x.js"`.
  // Lazy `import("./x.js")` screens are loaded on demand, not on startup.
  const pattern = /(?:^|\n)\s*(?:import|export)\b[^"'`;]*?from\s*["'](\.{1,2}\/[^"']+)["']|(?:^|\n)\s*import\s*["'](\.{1,2}\/[^"']+)["']/g;
  let match;
  while ((match = pattern.exec(source))) {
    const spec = match[1] || match[2];
    const next = path.posix.normalize(path.posix.join(path.posix.dirname(rel), spec));
    walk(next);
  }
}

walk("src/App.js");
const modules = [...seen].filter((rel) => rel.endsWith(".js") && fs.existsSync(path.join(root, rel))).sort();
const tags = modules.map((rel) => `    <link rel="modulepreload" href="/${rel}" />`).join("\n");

const indexPath = path.join(root, "index.html");
let html = fs.readFileSync(indexPath, "utf8");
const block = `    <!-- modulepreload:start (generated by scripts/build-shell.mjs) -->\n${tags}\n    <!-- modulepreload:end -->`;
if (/<!-- modulepreload:start[\s\S]*?modulepreload:end -->/.test(html)) {
  html = html.replace(/ *<!-- modulepreload:start[\s\S]*?modulepreload:end -->/, block);
} else {
  html = html.replace('<script type="module" src="/src/App.js"></script>', `${block}\n    <script type="module" src="/src/App.js"></script>`);
}
fs.writeFileSync(indexPath, html);
console.log(`modulepreload: ${modules.length} modules`);
